const goFabricModule = "github.com/SukramJ/go-fabric"

// defPackage is one typed cluster package of go-fabric
// (cluster/spec/<dir>, imported as <dir>def): its directory and the
// cluster Name its definition states.
type defPackage struct {
	dir  string
	name string
}

// goFabricDir is the directory of the go-fabric module this build uses —
// the module cache entry of the pinned version, or a replace target.
func goFabricDir() (string, error) {
	out, err := exec.CommandContext(context.Background(), "go", "list", "-m", "-f", "{{.Dir}}", goFabricModule).Output()
	if err != nil {
		var ee *exec.ExitError
		if errors.As(err, &ee) {
			return "", fmt.Errorf("go list -m %s: %w: %s", goFabricModule, err, ee.Stderr)
		}
		return "", fmt.Errorf("go list -m %s: %w", goFabricModule, err)
	}
	dir := strings.TrimSpace(string(out))
	if dir == "" {
		return "", fmt.Errorf("go list -m %s: no directory (is the module downloaded?)", goFabricModule)
	}
	return dir, nil
}

// defPackages lists go-fabric's typed cluster packages by cluster name: a
// directory under cluster/spec with a generated definition and server
// (definition_gen.go, server_gen.go) whose definition states its Name.
func defPackages() (map[string]defPackage, error) {
	root, err := goFabricDir()
	if err != nil {
		return nil, err
	}
	specDir := filepath.Join(root, "cluster", "spec")
	entries, err := os.ReadDir(specDir)
	if err != nil {
		return nil, err
	}
	out := map[string]defPackage{}
	for _, e := range entries {
		if !e.IsDir() {
			continue
		}
		dir := filepath.Join(specDir, e.Name())
		if _, err := os.Stat(filepath.Join(dir, "server_gen.go")); err != nil {
			continue
		}
		name, err := clusterName(filepath.Join(dir, "definition_gen.go"))
		if err != nil {
			return nil, err
		}
		if name == "" {
			continue
		}
		out[name] = defPackage{dir: e.Name(), name: name}
	}
	return out, nil
}

// clusterName is the string constant Name a definition file declares.
func clusterName(path string) (string, error) {
	f, err := parser.ParseFile(token.NewFileSet(), path, nil, parser.SkipObjectResolution)
	if err != nil {
		return "", err
	}
	for _, d := range f.Decls {
		gd, ok := d.(*ast.GenDecl)
		if !ok || gd.Tok != token.CONST {
			continue
		}
		for _, s := range gd.Specs {
			vs, ok := s.(*ast.ValueSpec)
			if !ok {
				continue
			}
			for i, n := range vs.Names {
				if n.Name != "Name" || i >= len(vs.Values) {
					continue
				}
				if lit, ok := vs.Values[i].(*ast.BasicLit); ok && lit.Kind == token.STRING {
					return strconv.Unquote(lit.Value)
				}
			}
		}
	}
	return "", nil
}

// bridgeSource is bridgeapi/clusters_gen.go: one entry per snapshot
// cluster go-fabric has a typed package for, in the snapshot's order —
// the per-cluster switch of the declaration decoder (brief S2 §1.3).
func (g *gen) bridgeSource(pkgs map[string]defPackage) ([]byte, error) {
	var imports, entries bytes.Buffer
	var missing []string
	for i := range g.s.Clusters {
		c := &g.s.Clusters[i]
		p, ok := pkgs[c.Name]
		if !ok {
			missing = append(missing, c.Name)
			continue
		}
		alias := p.dir + "def"
		fmt.Fprintf(&imports, "\t%s %q\n", alias, goFabricModule+"/cluster/spec/"+p.dir)
		fmt.Fprintf(&entries, "\t%[1]s.ClusterID: newKit[%[1]s.Patch, %[1]s.State, %[1]s.Declare](%[1]s.Name, %[1]s.Wrap),\n", alias)
	}
	var b bytes.Buffer
	b.WriteString("// Code generated by internal/gen from go-fabric's parity/schema.json and its cluster/spec packages. DO NOT EDIT.\n\n")
	b.WriteString("package bridgeapi\n\n")
	b.WriteString("import (\n")
	b.Write(imports.Bytes())
	b.WriteString(")\n\n")
	b.WriteString("// kits are the clusters a declaration may name: every cluster of the\n")
	b.WriteString("// snapshot go-fabric generates a typed package for, by cluster id.\n")
	if len(missing) > 0 {
		b.WriteString("// Without a typed package, and so not declarable: " + strings.Join(missing, ", ") + ".\n")
	}
	b.WriteString("var kits = map[uint32]clusterKit{\n")
	b.Write(entries.Bytes())
	b.WriteString("}\n")
	out, err := format.Source(b.Bytes())
	if err != nil {
		return b.Bytes(), fmt.Errorf("format: %w", err)
	}
	return out, nil
}

// declarationSchema is protocol/schema/declaration.schema.json: the JSON
// Schema of the bridge half's declaration document and of a set's patch,
// names not ids (brief S2 §1.3). Struct members are keyed by property
// name, the form a host writes.
func (g *gen) declarationSchema(pkgs map[string]defPackage) ([]byte, error) {
	defs := map[string]any{}
	clusterProps := map[string]any{}
	g.named = true
	defer func() { g.named = false }()
	for i := range g.s.Clusters {
		c := &g.s.Clusters[i]
		if _, ok := pkgs[c.Name]; !ok {
			continue
		}
		props := map[string]any{}
		for i := range c.Attributes {
			a := &c.Attributes[i]
			if a.ID >= 0xF000 {
				continue
			}
			s := g.valueSchema(a.Effective, c, defs)
			s["title"] = a.Name
			if a.Effective.Quality.Nullable {
				s = nullable(s)
			}
			props[camelize(a.Name)] = s
		}
		defs["patch."+c.Name] = map[string]any{
			"title":                c.Name + " patch",
			"description":          fmt.Sprintf("A change to the %s cluster (0x%04X, revision %d): attributes by property name, matched without regard to case; null sets a nullable attribute to null.", c.Name, c.ID, c.Revision),
			"type":                 "object",
			"properties":           props,
			"additionalProperties": false,
		}
		features := make([]string, 0, 2*len(c.Features))
		for _, f := range c.Features {
			features = append(features, f.Effective.Title, f.Name)
		}
		var commands []string
		for i := range c.Commands {
			if d, _, _ := g.command(c, &c.Commands[i]); d == "request" {
				commands = append(commands, c.Commands[i].Name)
			}
		}
		entry := map[string]any{
			"initial":       map[string]any{"$ref": "#/$defs/patch." + c.Name},
			"handle_writes": map[string]any{"type": "boolean", "description": "the host answers each controller write of this cluster (the write event)"},
		}
		if len(features) > 0 {
			entry["features"] = map[string]any{"type": "array", "items": map[string]any{"enum": features}, "uniqueItems": true}
		}
		if len(commands) > 0 {
			entry["handle_commands"] = map[string]any{"type": "array", "items": map[string]any{"enum": commands}, "uniqueItems": true}
		}
		defs["cluster."+c.Name] = map[string]any{
			"title":                c.Name,
			"type":                 "object",
			"properties":           entry,
			"additionalProperties": false,
		}
		clusterProps[c.Name] = map[string]any{"$ref": "#/$defs/cluster." + c.Name}
	}
	types := make([]string, 0, len(g.s.DeviceTypes))
	for _, d := range g.s.DeviceTypes {
		types = append(types, d.Name)
	}
	sort.Strings(types)
	str := map[string]any{"type": "string"}
	defs["device"] = map[string]any{
		"title": "device",
		"type":  "object",
		"properties": map[string]any{
			"key":             map[string]any{"type": "string", "minLength": 1, "description": "the host's stable key: the device keeps its endpoint number under it"},
			"type":            map[string]any{"enum": types, "description": "the device type by name"},
			"name":            str,
			"vendor":          str,
			"device_address":  str,
			"channel_address": str,
			"reachable":       map[string]any{"type": "boolean"},
			"clusters":        map[string]any{"type": "object", "properties": clusterProps, "additionalProperties": false},
		},
		"required":             []string{"key", "type"},
		"additionalProperties": false,
	}
	doc := map[string]any{
		"$schema":                "https://json-schema.org/draft/2020-12/schema",
		"$id":                    "https://github.com/SukramJ/go-fabric-server/protocol/schema/declaration.schema.json",
		"title":                  "go-fabric-server bridge declaration",
		"description":            "The declare document of the bridge half (/bridge): the devices, their device type by name and their clusters by name with the initial state. $defs/patch.<Cluster> is the patch of a set. Names are matched without regard to case.",
		"x-go-fabric-version":    g.version,
		"x-matter-revision":      g.s.Matter.Revision,
		"x-matter-source-commit": g.s.Matter.SourceCommit,
		"type":                   "object",
		"properties": map[string]any{
			"devices": map[string]any{"type": "array", "items": map[string]any{"$ref": "#/$defs/device"}},
		},
		"required":             []string{"devices"},
		"additionalProperties": false,
		"$defs":                defs,
	}
	var b bytes.Buffer
	enc := json.NewEncoder(&b)
	enc.SetEscapeHTML(false)
	enc.SetIndent("", " ")
	if err := enc.Encode(doc); err != nil {
		return nil, err
	}
	return b.Bytes(), nil
}
